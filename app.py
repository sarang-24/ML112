# Import necessary libraries
import json # Used to load the summary metrics from a JSON file
import joblib # Used to load the trained machine learning model
import pandas as pd # Used for data manipulation, creating dataframes for prediction
import streamlit as st # The framework used to create the web dashboard

# Configure the Streamlit page layout and title
st.set_page_config(page_title="Product Demand Prediction", page_icon="📦", layout="wide")

# @st.cache_resource ensures the model and summary are loaded only once and cached, saving time on reload
@st.cache_resource
def load():
    # Load the trained model and the summary JSON file generated by train.py
    return joblib.load("models/best_model.joblib"), json.load(open("outputs/summary.json"))

# Assign the loaded model and summary to variables
model, summary = load()

# Set the main title of the dashboard
st.title("📦 Product Demand Prediction using Machine Learning")

# Display a caption with the best model's name and its performance metrics (R-squared and Mean Absolute Error)
st.caption(f"Best model: **{summary['best_model']}**  |  R² = {summary['metrics']['R2']:.3f}  |  "
           f"MAE = {summary['metrics']['MAE']:.2f} units")

# Create 3 separate tabs for different functionalities
tab1, tab2, tab3 = st.tabs(["🔮 Predict Demand", "📊 Model Comparison", "💡 Insights"])

# --- TAB 1: PREDICT DEMAND ---
with tab1:
    # Split the layout into 2 columns for better organization of input fields
    c1, c2 = st.columns(2)
    
    # Left column inputs
    with c1:
        category = st.selectbox("Product category", ["Electronics", "Clothing", "Groceries", "Home & Kitchen", "Toys", "Sports"])
        hist = st.number_input("Historical demand (units)", 0, 5000, 100) # Baseline demand
        price = st.number_input("Product price", 0.5, 5000.0, 50.0) # Current price
        discount = st.slider("Discount (%)", 0, 50, 10) # Discount offered
        
    # Right column inputs
    with c2:
        promo = st.radio("Promotion running?", ["No", "Yes"], horizontal=True) # Is there an active marketing promo?
        season = st.selectbox("Season", ["Winter", "Spring", "Summer", "Autumn"]) # Current season
        holiday = st.radio("Holiday period?", ["No", "Yes"], horizontal=True) # Is it a holiday season?
        prev = st.number_input("Previous month sales (units)", 0, 5000, 100) # Sales from last month
        stock = st.number_input("Current stock on hand (units)", 0, 10000, 80) # How many items we currently have

    # When the user clicks the predict button
    if st.button("Predict Expected Demand", type="primary"):
        # Combine all user inputs into a single Pandas DataFrame row, formatting binary variables (Yes/No) to 1/0
        X = pd.DataFrame([{
            "product_category": category, "season": season, "historical_demand": hist,
            "product_price": price, "discount": discount, "promotion": int(promo == "Yes"),
            "holiday": int(holiday == "Yes"), "previous_month_sales": prev}])
        
        # Predict the demand using the loaded machine learning model, ensure it's not negative, and round to a whole number
        pred = max(0, round(float(model.predict(X)[0])))
        
        # Get the recommended safety stock from our JSON summary to prevent stockouts
        safety = summary["safety_stock_units"]
        
        # Calculate how many items we need to order (Predicted Demand + Safety Stock - What we already have)
        reorder = max(0, round(pred + safety - stock))
        
        # Display the predicted demand prominently
        st.success(f"### Expected Product Demand: **{pred} units**")
        
        # Display 3 key metrics underneath the prediction
        m1, m2, m3 = st.columns(3)
        m1.metric("Safety stock (95%)", f"{safety:.0f}")
        m2.metric("Current stock", stock)
        m3.metric("Suggested reorder qty", reorder)
        
        # Provide logic-based warnings about inventory health
        if stock > pred + safety * 2:
            st.warning("⚠️ Overstock risk: stock far exceeds predicted demand.")
        elif stock < pred:
            st.error("🚨 Stock-out risk: current stock is below predicted demand.")
        else:
            st.info("✅ Stock level is healthy.")

# --- TAB 2: MODEL COMPARISON ---
with tab2:
    # Display the comparison of all models trained in a formatted table
    st.dataframe(pd.read_csv("outputs/model_comparison.csv").round(3), use_container_width=True)
    # Display the bar chart comparing model metrics
    st.image("outputs/model_comparison.png")
    # Display the scatter plot showing Actual vs Predicted values for the best model
    st.image("outputs/actual_vs_pred.png", width=450)

# --- TAB 3: INSIGHTS ---
with tab3:
    # Display Exploratory Data Analysis (EDA) charts
    st.image("outputs/eda.png")
    # Display which features were most important to the model's decision making
    st.image("outputs/feature_importance.png", width=550)
    # Read and display the final markdown report generated during training
    st.markdown(open("outputs/final_analysis.md").read())
